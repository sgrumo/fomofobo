export const PIXEL_ICON_GRID = 12

/**
 * @description Builds an SVG path that fills every `#` cell of the bitmap, one rectangle per horizontal run
 * @param rows Bitmap rows, `#` filled and `.` empty
 */
export const pixelIconPath = (rows: readonly string[]): string =>
    rows
        .flatMap((row, y) =>
            [...row.matchAll(/#+/gu)].map(
                run =>
                    `M${String(run.index)} ${String(y)}h${String(run[0].length)}v1h-${String(run[0].length)}z`,
            ),
        )
        .join("")
